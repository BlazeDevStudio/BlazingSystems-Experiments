#!/bin/sh
set -eu
ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
L="$ROOT/android/BlazeRentalLauncher"
N="$L/src/com/google/android/apps/nexuslauncher/NexusLauncherActivity.java"
M="$L/src/com/blazesystems/blazerental/ManagedPolicyController.java"
A="$L/src/com/blazesystems/blazerental/BlazeAdminActivity.java"
C="$L/src/com/blazesystems/blazerental/LeaseClient.java"
P="$L/src/com/blazesystems/blazerental/ManagedPolicyController.java"
U="$L/src/com/blazesystems/blazerental/RentalUiPolicy.java"
LAC="$L/src/com/blazesystems/blazerental/LauncherAccessController.java"
LAUNCHER="$L/src/com/android/launcher3/Launcher.java"
PAGES="$L/src/com/blazesystems/blazerental/RentalSystemPages.java"

grep -Fq 'ManagedPolicyController.enforceLauncherTask(this);' "$N"
grep -Fq 'setUninstallBlocked(admin, context.getPackageName(), true)' "$M"
grep -Fq 'ApplicationInfo.FLAG_DEBUGGABLE' "$M"
grep -Fq 'DISALLOW_DEBUGGING_FEATURES' "$M"
grep -Fq 'TRANSFER TO ANOTHER SERVER / RUN INITIAL SETUP' "$A"
grep -Fq 'SAVE APP ALLOW / HIDE POLICY' "$A"
grep -Fq 'InitialSetupPolicy' "$L/tests/unit/com/blazesystems/blazerental/InitialSetupPolicyTest.java"
grep -Fq 'installedLaunchablePackages' "$P"
grep -Fq 'ManagedPolicyController.installedLaunchablePackages(context)' "$C"
grep -Fq 'policy_sig_v3' "$C"
grep -Fq 'RentalUiPolicy.applyVerified' "$C"
grep -Fq 'operator_quick_controls' "$U"
grep -Fq 'canLaunchIntent' "$LAC"
grep -Fq 'canOpenAppDrawer' "$LAC"
grep -Fq 'policy.isPackageAllowed(app.componentName.getPackageName())' "$LAC"
grep -Fq 'LauncherAccessController.canLaunchIntent(this, intent)' "$LAUNCHER"
grep -Fq 'currentBlazeRevision != mBlazePolicyRevision' "$LAUNCHER"
grep -Fq 'setOuterInterceptionBlocked(true)' "$PAGES"
grep -Fq 'setOuterInterceptionBlocked(false)' "$PAGES"
grep -Fq 'requestDisallowInterceptTouchEvent(blocked)' "$PAGES"
STORE="$L/src/com/blazesystems/blazerental/RentalLeaseStore.java"
BOOT="$L/src/com/blazesystems/blazerental/BlazeBootReceiver.java"
grep -Fq 'RentalLeaseStore.invalidateLeaseAfterBoot(context)' "$BOOT"
grep -Fq 'AdminBootPolicy.lockedUntilAfterReboot(' "$STORE"
grep -Fq '.remove("admin_unlock_until")' "$STORE"
grep -Fq 'AdminBootPolicy.LOCKOUT_MS' "$STORE"
echo "v0.4 Android source contract passed"
